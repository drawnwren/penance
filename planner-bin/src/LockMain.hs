import Distribution.Fields.ParseResult (runParseResult)
import Distribution.PackageDescription
  ( Benchmark (..)
  , BenchmarkInterface (..)
  , BuildInfo (..)
  , Executable (..)
  , Library (..)
  , PackageDescription (..)
  , TestSuite (..)
  , TestSuiteInterface (..)
  , buildType
  , pkgName
  , pkgVersion
  )
